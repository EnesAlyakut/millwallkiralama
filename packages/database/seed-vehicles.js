async function seed() {
  console.log('Seeding new vehicles...');

  // Cache categories
  const categories = await db.category.findMany();
  const catMap = {};
  categories.forEach(c => catMap[c.slug] = c.id);

  let added = 0;

  for (const v of vehiclesToSeed) {
    const categoryId = catMap[v.categorySlug];
    if (!categoryId) {
      console.log(`Kategori bulunamadı: ${v.categorySlug}`);
      continue;
    }

    const slug = generateSlug(v.name);
    // Extract model by removing brand from name
    const model = v.name.replace(v.brand + ' ', '');
    
    // Check if exists
    const existing = await db.vehicle.findUnique({ where: { slug } });
    if (existing) {
      console.log(`Zaten var: ${v.name}`);
      continue;
    }

    await db.vehicle.create({
      data: {
        categoryId,
        name: v.name,
        slug,
        brand: v.brand,
        model: model,
        year: v.year,
        fuelType: v.fuel,
        transmission: v.transmission,
        seatCount: v.seats,
        doorCount: v.doors,
        trunkCapacity: v.luggage,
        dailyPrice: v.dailyPrice,
        techFeatures: v.features,
        description: v.description,
        status: 'AVAILABLE',
        featured: false,
      }
    });
    added++;
    console.log(`Eklendi: ${v.name}`);
  }

  console.log(`\nToplam ${added} yeni araç sisteme eklendi.`);
}

seed().catch(console.error).finally(() => db.$disconnect());
